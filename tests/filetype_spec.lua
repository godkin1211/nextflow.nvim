local filetype = require("nextflow.filetype")

describe("filetype", function()
  filetype.setup()
  local proj = vim.fn.resolve(vim.fn.tempname())
  vim.fn.mkdir(proj .. "/conf", "p")
  vim.fn.writefile({}, proj .. "/nextflow.config")

  local function ft(path)
    return vim.filetype.match({ filename = path })
  end

  it("detects *.nf", function() assert.equals("nextflow", ft(proj .. "/main.nf")) end)
  it("detects nextflow.config", function() assert.equals("nextflow", ft(proj .. "/nextflow.config")) end)
  it("detects *.config inside a Nextflow project", function()
    assert.equals("nextflow", ft(proj .. "/conf/base.config"))
  end)
  it("leaves *.config outside a Nextflow project alone", function()
    local other = vim.fn.resolve(vim.fn.tempname())
    vim.fn.mkdir(other, "p")
    assert.is_true(ft(other .. "/foo.config") ~= "nextflow")
  end)
  it("treats *.nf.test as groovy", function() assert.equals("groovy", ft("/x/tests/main.nf.test")) end)
  it("treats nf-test.config as groovy", function() assert.equals("groovy", ft(proj .. "/nf-test.config")) end)
  it("uses the groovy parser for nextflow", function()
    assert.equals("groovy", vim.treesitter.language.get_lang("nextflow"))
  end)
  it("is idempotent", function()
    filetype.setup()
    assert.equals("nextflow", ft(proj .. "/main.nf"))
  end)
end)
