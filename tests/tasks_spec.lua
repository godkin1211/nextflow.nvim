local tasks = require("nextflow.tasks")

local work = vim.fn.tempname()
local stdout = table.concat(vim.fn.readfile("tests/fixtures/nextflow_log.tsv"), "\n"):gsub("{WORK}", work)

describe("tasks.parse", function()
  it("reads one task per tab-separated line", function()
    local list = tasks.parse(stdout)
    assert.equals(4, #list)
    assert.same({
      status = "FAILED", exit = "1", name = "PIPE:ALIGN (s1)", hash = "d1/34613f",
      duration = "12s", workdir = work .. "/d1/34613f",
    }, list[2])
  end)
  it("returns an empty list for empty output", function()
    assert.same({}, tasks.parse(""))
    assert.same({}, tasks.parse("\n"))
  end)
end)

describe("tasks.sort", function()
  it("puts FAILED, then ABORTED, first and keeps log order otherwise", function()
    local statuses = vim.tbl_map(function(t) return t.status end, tasks.sort(tasks.parse(stdout)))
    assert.same({ "FAILED", "ABORTED", "COMPLETED", "CACHED" }, statuses)
  end)
end)

describe("tasks.label", function()
  it("shows marker, exit, name, duration and hash", function()
    assert.equals("✗ [1] PIPE:ALIGN (s1)  12s  d1/34613f", tasks.label(tasks.parse(stdout)[2]))
    assert.equals("↺ [0] PIPE:INDEX  6m 10s  c4/9901d4", tasks.label(tasks.parse(stdout)[3]))
  end)
end)

describe("tasks.files", function()
  it("lists existing .command files in a fixed order, then the directory", function()
    local d = work .. "/d1/34613f"
    vim.fn.mkdir(d, "p")
    vim.fn.writefile({ "boom" }, d .. "/.command.sh")
    vim.fn.writefile({ "boom" }, d .. "/.command.err")
    local labels = vim.tbl_map(function(f) return f.label end, tasks.files(d))
    assert.same({ ".command.err", ".command.sh", "open work directory" }, labels)
    assert.equals(d .. "/.command.err", tasks.files(d)[1].path)
  end)
  it("returns nothing for a cleaned-up work directory", function()
    assert.same({}, tasks.files("/no/such/dir"))
    assert.same({}, tasks.files("-"))
  end)
end)

describe("tasks.failed_file", function()
  it("prefers a non-empty .command.err, else .command.log", function()
    local d = vim.fn.tempname()
    vim.fn.mkdir(d, "p")
    vim.fn.writefile({}, d .. "/.command.err")
    vim.fn.writefile({ "log" }, d .. "/.command.log")
    assert.equals(d .. "/.command.log", tasks.failed_file(d))
    vim.fn.writefile({ "err" }, d .. "/.command.err")
    assert.equals(d .. "/.command.err", tasks.failed_file(d))
    assert.is_nil(tasks.failed_file("/no/such/dir"))
  end)
end)
