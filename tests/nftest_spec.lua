local nftest = require("nextflow.nftest")

describe("nftest.alt_path", function()
  it("maps an nf-core style main.nf to tests/main.nf.test and back", function()
    assert.equals("/p/modules/x/tests/main.nf.test", nftest.alt_path("/p/modules/x/main.nf"))
    assert.equals("/p/modules/x/main.nf", nftest.alt_path("/p/modules/x/tests/main.nf.test"))
  end)
  it("maps foo.nf to tests/foo.nf.test and back", function()
    assert.equals("/p/tests/foo.nf.test", nftest.alt_path("/p/foo.nf"))
    assert.equals("/p/foo.nf", nftest.alt_path("/p/tests/foo.nf.test"))
  end)
  it("maps a test outside tests/ to the same directory", function()
    assert.equals("/p/a.nf", nftest.alt_path("/p/a.nf.test"))
  end)
  it("returns nil for other files", function()
    assert.is_nil(nftest.alt_path("/p/nextflow.config"))
  end)
end)

describe("nftest.enclosing_test", function()
  local lines = vim.fn.readfile("tests/fixtures/sample.nf.test")
  it("finds the test block around the cursor with its ordinal", function()
    assert.same({ "first", 1 }, { nftest.enclosing_test(lines, 7) })
    assert.same({ "second", 2 }, { nftest.enclosing_test(lines, 12) })
    assert.same({ "second", 2 }, { nftest.enclosing_test(lines, 11) })
  end)
  it("returns nil outside any test block", function()
    assert.is_nil(nftest.enclosing_test(lines, 2))
    assert.is_nil(nftest.enclosing_test(lines, 10))
  end)
  it("handles single-quoted names", function()
    assert.same({ "q", 1 }, { nftest.enclosing_test({ "test('q') {", "  x", "}" }, 2) })
  end)
end)

describe("nftest.parse_list", function()
  it("parses real `nf-test list --silent` output, ANSI colours included", function()
    local out = table.concat(vim.fn.readfile("tests/fixtures/nftest_list.txt"), "\n")
    assert.same({
      { path = "tests/main.nf.test", hash = "3b6f5e0d", name = "first" },
      { path = "tests/main.nf.test", hash = "93d49ea1", name = "second" },
    }, nftest.parse_list(out))
  end)
  it("keeps duplicate names in file order", function()
    local list = nftest.parse_list("  [t.nf.test@aaaa1111] dup\n  [t.nf.test@bbbb2222] dup\n")
    assert.equals(2, #list)
    assert.equals("bbbb2222", list[2].hash)
  end)
end)

describe("nftest.pick_entry", function()
  local list = {
    { hash = "a", name = "dup" }, { hash = "b", name = "dup" }, { hash = "c", name = "other" },
  }
  it("uses the ordinal when its name matches", function()
    assert.equals("b", nftest.pick_entry(list, "dup", 2).hash)
  end)
  it("falls back to the first entry with that name", function()
    assert.equals("c", nftest.pick_entry(list, "other", 1).hash)
  end)
  it("returns nil when the name is unknown", function()
    assert.is_nil(nftest.pick_entry(list, "missing", 1))
  end)
end)
