local nfcore = require("nextflow.nfcore")

describe("nfcore.parse_remote", function()
  it("returns the module names sorted", function()
    assert.same({ "a/x", "b" }, nfcore.parse_remote('["b","a/x"]'))
  end)
  it("returns an empty list for non-JSON output", function()
    assert.same({}, nfcore.parse_remote("ERROR could not reach GitHub"))
  end)
end)

describe("nfcore.parse_local", function()
  it("parses real `modules list local --json` stdout, which starts with an INFO log line", function()
    local out = table.concat(vim.fn.readfile("tests/fixtures/modules_local.json"), "\n")
    assert.same({ "fastqc", "multiqc" }, nfcore.parse_local(out))
  end)
end)

describe("nfcore.cache_fresh", function()
  local path = vim.fn.tempname()
  vim.fn.writefile({ "[]" }, path)
  local mtime = vim.uv.fs_stat(path).mtime.sec
  it("is fresh within the ttl", function()
    assert.is_true(nfcore.cache_fresh(path, 86400, mtime + 10))
  end)
  it("is stale after the ttl", function()
    assert.is_false(nfcore.cache_fresh(path, 86400, mtime + 90000))
  end)
  it("is not fresh when the file is missing", function()
    assert.is_false(nfcore.cache_fresh(path .. ".missing", 86400, mtime))
  end)
end)

describe("nfcore.cache_path", function()
  it("lives in the plugin's cache dir", function()
    assert.equals(vim.fn.stdpath("cache") .. "/nextflow.nvim/remote_modules.json", nfcore.cache_path())
  end)
end)
