local params = require("nextflow.params")

local defs = params.load(vim.fn.fnamemodify("tests/fixtures/schema_defs.json", ":p"))
local flat = params.load(vim.fn.fnamemodify("tests/fixtures/schema_flat.json", ":p"))

describe("params.lookup", function()
  it("finds params inside $defs groups", function()
    local entry, required = params.lookup(defs, "genome")
    assert.truthy(vim.tbl_contains(entry.enum, "GRCh38"))
    assert.is_false(required)
    local _, input_required = params.lookup(defs, "input")
    assert.is_true(input_required)
  end)
  it("finds params in top-level properties", function()
    local entry, required = params.lookup(flat, "input")
    assert.equals("Samplesheet", entry.description)
    assert.is_true(required)
  end)
  it("returns nil for params missing from the schema", function()
    assert.is_nil(params.lookup(defs, "nope"))
    assert.is_nil(params.lookup(flat, "nope"))
  end)
end)

describe("params.flatten", function()
  it("merges every group into one draft-07 object schema", function()
    local f = params.flatten(defs)
    assert.equals("http://json-schema.org/draft-07/schema#", f["$schema"])
    assert.equals("object", f.type)
    assert.truthy(f.properties.outdir)
    assert.truthy(f.properties.genome)
    assert.truthy(vim.tbl_contains(f.required, "input"))
    assert.is_nil(f["$defs"])
    assert.is_nil(f.allOf)
  end)
  it("keeps top-level properties and required", function()
    local f = params.flatten(flat)
    assert.truthy(f.properties.kmer_size)
    assert.same({ "input" }, f.required)
  end)
end)

describe("params.word_at", function()
  it("returns the param name under the cursor", function()
    assert.equals("kmer_size", params.word_at("  x = params.kmer_size + 1", 15))
    assert.equals("kmer_size", params.word_at("  x = params.kmer_size + 1", 6))
  end)
  it("returns nil when the cursor is not on params.<name>", function()
    assert.is_nil(params.word_at("x = 1", 2))
    assert.is_nil(params.word_at("  x = params.kmer_size + 1", 24))
  end)
end)

describe("params.format_entry", function()
  it("renders type, description, default, enum and required", function()
    local entry, required = params.lookup(defs, "genome")
    local text = table.concat(params.format_entry("genome", entry, required), "\n")
    assert.truthy(text:find("`params.genome`", 1, true))
    assert.truthy(text:find("string", 1, true))
    assert.truthy(text:find("Name of iGenomes reference.", 1, true))
    assert.truthy(text:find("GRCh37", 1, true))
    assert.truthy(text:find("GRCh38", 1, true))
    local e2, r2 = params.lookup(defs, "input")
    local t2 = table.concat(params.format_entry("input", e2, r2), "\n")
    assert.truthy(t2:find("required", 1, true))
    assert.truthy(t2:find("help_text", 1, true) or t2:find("Use this to specify", 1, true))
    assert.truthy(t2:find("^\\S+\\.csv$", 1, true))
  end)
end)

describe("params.is_params_file", function()
  it("matches params*.yml/yaml/json only", function()
    assert.is_true(params.is_params_file("/p/params.yml"))
    assert.is_true(params.is_params_file("/p/params-test.yaml"))
    assert.is_true(params.is_params_file("/p/params_dev.json"))
    assert.is_false(params.is_params_file("/p/samplesheet.yml"))
    assert.is_false(params.is_params_file("/p/nextflow_schema.json"))
  end)
end)
